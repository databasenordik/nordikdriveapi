-- Internal current-record view. Runtime does not get SELECT on this object.

CREATE OR REPLACE VIEW assistant_api.v_current_records AS
SELECT
    n.id,
    n.source_row_id,
    n.file_id,
    n.version,
    n.row_data_normalized,
    n.search_text,
    n.canonical_name,
    n.canonical_community,
    n.canonical_school,
    n.source_created_at,
    n.source_updated_at,
    f.filename,
    f.private
FROM public.file_data_normalized n
JOIN public.file f
  ON f.id = n.file_id
 AND f.version = n.version
WHERE COALESCE(f.is_delete, false) = false
  AND n.status = 'ready';

CREATE OR REPLACE VIEW assistant_api.v_current_raw_records AS
SELECT
    d.id,
    d.file_id,
    d.version,
    d.row_data,
    f.filename,
    f.private
FROM public.file_data d
JOIN public.file f
  ON f.id = d.file_id
 AND f.version = d.version
WHERE COALESCE(f.is_delete, false) = false;

CREATE OR REPLACE VIEW assistant_api.v_datasets AS
SELECT
    f.id AS file_id,
    f.filename,
    f.description,
    f.version AS current_version,
    f.private,
    p.enabled AS assistant_enabled,
    p.user_facing_label,
    p.is_default_people_scope
FROM public.file f
JOIN assistant.dataset_policy p ON p.file_id = f.id
WHERE COALESCE(f.is_delete, false) = false;

CREATE OR REPLACE VIEW assistant_api.v_dataset_fields AS
SELECT
    r.file_id,
    r.semantic_field,
    r.human_label,
    r.aliases,
    r.canonical_json_path,
    r.raw_json_keys,
    r.semantic_type,
    r.allowed_operators,
    r.searchable,
    r.aggregatable,
    r.sortable,
    r.quoteable,
    r.sensitivity,
    r.exposure_policy
FROM assistant.field_registry r;

CREATE OR REPLACE VIEW assistant_api.v_reference_entities AS
SELECT
    'community'::text AS entity_type,
    c.id,
    c.community_name::text AS name,
    ARRAY[c.community_name::text] AS variants
FROM public.communities c
UNION ALL
SELECT
    'day_school',
    d.id,
    d.school_name AS name,
    ARRAY_REMOVE(
        ARRAY[d.school_name] || COALESCE(regexp_split_to_array(d.name_variants, '\\s*[;,]\\s*'), ARRAY[]::TEXT[]),
        NULL
    ) AS variants
FROM public.day_schools d
UNION ALL
SELECT
    'indian_hospital',
    h.id,
    h.hospital_name AS name,
    ARRAY_REMOVE(
        ARRAY[h.hospital_name] || COALESCE(regexp_split_to_array(h.name_variants, '\\s*[;,]\\s*'), ARRAY[]::TEXT[]),
        NULL
    ) AS variants
FROM public.indian_hospitals h
UNION ALL
SELECT 'province', p.id, p.name, ARRAY[p.name] FROM public.provinces p;

CREATE OR REPLACE FUNCTION assistant_api._authorized_file_ids(
    p_principal_id TEXT,
    p_requested_file_ids INTEGER[],
    p_can_use_private BOOLEAN
)
RETURNS INTEGER[]
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = assistant_api, assistant, public
AS $$
    SELECT COALESCE(array_agg(f.id), ARRAY[]::INTEGER[])
    FROM public.file f
    JOIN assistant.dataset_policy p ON p.file_id = f.id
    WHERE p.enabled = TRUE
      AND COALESCE(f.is_delete, false) = false
      AND f.id = ANY (p_requested_file_ids)
      AND (
            f.private = FALSE
            OR (
                p_can_use_private
                AND EXISTS (
                    SELECT 1
                    FROM assistant.access_grants g
                    WHERE g.principal_id = p_principal_id
                      AND g.file_id = f.id
                      AND g.grant_status = 'active'
                      AND (g.expires_at IS NULL OR g.expires_at > now())
                )
            )
      );
$$;

CREATE OR REPLACE FUNCTION assistant_api.list_datasets(
    p_principal_id TEXT,
    p_requested_file_ids INTEGER[],
    p_can_use_private BOOLEAN
)
RETURNS TABLE (
    file_id INTEGER,
    filename TEXT,
    description TEXT,
    current_version INTEGER,
    private BOOLEAN,
    assistant_enabled BOOLEAN,
    user_facing_label TEXT,
    is_default_people_scope BOOLEAN
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = assistant_api, assistant, public
AS $$
    SELECT
        d.file_id,
        d.filename,
        d.description,
        d.current_version,
        d.private,
        d.assistant_enabled,
        d.user_facing_label,
        d.is_default_people_scope
    FROM assistant_api.v_datasets d
    WHERE d.file_id = ANY (
        assistant_api._authorized_file_ids(p_principal_id, p_requested_file_ids, p_can_use_private)
    )
    ORDER BY d.file_id;
$$;

